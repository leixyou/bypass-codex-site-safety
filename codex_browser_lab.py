# --------------------------------------------------------------------------
# TOML surgery (text-level, so comments/ordering elsewhere survive)
# --------------------------------------------------------------------------
def table_span(text: str, name: str) -> tuple[int, int] | None:
    start = None
    for m in re.finditer(r"(?m)^\[([^\]]+)\][ \t]*\r?\n", text):
        if m.group(1) == name and start is None:
            start = m.start()
            continue
        if start is not None:
            return start, m.start()
    if start is None:
        return None
    return start, len(text)


def ensure_table(text: str, table: str) -> str:
    """Create `[table]` (right after its parent table) when it does not exist."""
    if table_span(text, table) is not None:
        return text
    block = f"[{table}]\n"
    if "." in table:
        parent = table.rsplit(".", 1)[0]
        span = table_span(text, parent)
        if span is not None:
            head = text[: span[1]].rstrip("\n")
            return f"{head}\n\n{block}\n{text[span[1] :]}"
    return text.rstrip("\n") + f"\n\n{block}"


def set_key(text: str, table: str, key: str, value: str) -> str:
    span = table_span(text, table)
    if span is None:
        raise SystemExit(f"missing TOML table [{table}] in {config_toml()}")
    body = text[span[0] : span[1]]
    pattern = re.compile(rf"(?m)^({re.escape(key)}\s*=\s*).+$")
    quoted = json.dumps(value, ensure_ascii=False)
    if pattern.search(body):
        body = pattern.sub(rf"\1{quoted}", body, count=1)
    else:
        lines = body.splitlines(keepends=True)
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        insert_at = len(lines)
        for i, line in enumerate(lines):
            if line.startswith("BROWSER_USE_TINYSKY_ENABLED") or line.startswith(
                "BROWSER_USE_AVAILABLE_BACKENDS"
            ):
                insert_at = i + 1
        lines.insert(insert_at, f"{key} = {quoted}\n")
        body = "".join(lines)
    return text[: span[0]] + body + text[span[1] :]


def remove_key(text: str, table: str, key: str) -> str:
    span = table_span(text, table)
    if span is None:
        return text
    body = text[span[0] : span[1]]
    body = re.sub(rf"(?m)^{re.escape(key)}\s*=\s*.+\r?\n?", "", body)
    return text[: span[0]] + body + text[span[1] :]


def get_key(text: str, table: str, key: str) -> str | None:
    span = table_span(text, table)
    if span is None:
        return None
    m = re.search(
        rf"""(?m)^\s*{re.escape(key)}\s*=\s*(['"])(.*?)\1\s*$""",
        text[span[0] : span[1]],
    )
    return m.group(2) if m else None


def origin_table(host_pattern: str) -> str:
    return (
        f'[browser_use.origins."{host_pattern}"]\n'
        "access = \"allow\"\n"
        "downloads = \"allow\"\n"
        "uploads = \"allow\"\n"
        "full_cdp_access = \"allow\"\n"
    )


def ensure_origin_tables(text: str, domains: list[str]) -> str:
    blocks: list[str] = []
    for domain in domains:
        for key in (f"https://{domain}", f"https://**.{domain}"):
            header = f'[browser_use.origins."{key}"]'
            if header in text:
                continue
            blocks.append(origin_table(key).rstrip())
    if not blocks:
        return text
    addon = "\n\n" + "\n\n".join(blocks) + "\n"
    last_name = None
    for m in re.finditer(r"(?m)^\[(browser_use\.origins\.[^\]]+)\]", text):
        last_name = m.group(1)
    if last_name:
        span = table_span(text, last_name)
        assert span is not None
        return text[: span[1]].rstrip() + addon + text[span[1] :]
    span = table_span(text, "mcp_servers.node_repl.env")
    if span is not None:
        return text[: span[1]].rstrip() + addon + text[span[1] :]
    return text.rstrip() + addon


def merge_allowed_array(text: str, table: str, urls: list[str]) -> str:
    span = table_span(text, table)
    if span is None:
        return text
    body = text[span[0] : span[1]]
    m = re.search(r"(?ms)^(allowed\s*=\s*)\[(.*?)\]", body)
    if not m:
        return text
    existing = re.findall(r'"([^"]+)"', m.group(2))
    merged = list(existing)
    for url in urls:
        if url not in merged:
            merged.append(url)
    if merged == existing:
        return text
    inner = ",\n".join(f'  "{u}"' for u in merged)
    new_array = f"{m.group(1)}[\n{inner},\n]"
    body = body[: m.start()] + new_array + body[m.end() :]
    return text[: span[0]] + body + text[span[1] :]


