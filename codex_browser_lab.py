def backup(path: Path) -> None:
    """Copy `path` aside before it is rewritten.

    The backup name is derived from the path *relative to CODEX_HOME*, so files
    that share a basename (`config.toml` vs `browser/config.toml`) can never
    overwrite each other's backup.
    """
    if not path.exists():
        return
    dest_dir = wrappers_dir() / "backups"
    dest_dir.mkdir(parents=True, exist_ok=True)
    try:
        rel = path.resolve().relative_to(codex_home().resolve())
        stem = "_".join(rel.parts)
    except (ValueError, OSError):
        stem = path.name
    stamp = datetime.now().strftime("%Y%m%d%H%M%S")
    dest = dest_dir / f"{stem}.{stamp}"
    n = 2
    while dest.exists():
        dest = dest_dir / f"{stem}.{stamp}-{n}"
        n += 1
    shutil.copy2(path, dest)


def ensure_wrapper(*, dry: bool, quiet: bool) -> Path:
    path = wrapper_path()
    if dry:
        return path
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or read_text(path) != WRAPPER_BODY:
        write_text(path, WRAPPER_BODY)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    log(f"wrapper: {path}", quiet=quiet)
    return path


def patch_config(domains: list[str], *, dry: bool, quiet: bool) -> bool:
    path = config_toml()
    if not path.exists():
        raise SystemExit(f"missing {path}; is Codex/ChatGPT installed?")
    text = read_text(path)
    if table_span(text, "mcp_servers.node_repl") is None:
        raise SystemExit(f"no [mcp_servers.node_repl] in {path}")
    original = text
    if IS_WIN:
        # Codex hands this env table straight to node_repl.exe; no wrapper needed.
        text = ensure_table(text, "mcp_servers.node_repl.env")
        text = set_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE", MODE)
    else:
        text = set_key(text, "mcp_servers.node_repl", "command", str(wrapper_path()))
        text = ensure_table(text, "mcp_servers.node_repl.env")
        text = set_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE", MODE)
    if domains:
        text = ensure_origin_tables(text, domains)
    if text == original:
        log(f"unchanged: {path}", quiet=quiet)
        return False
    if dry:
        log(f"would patch: {path}", quiet=quiet)
        return True
    backup(path)
    write_text(path, text)
    log(f"patched: {path}", quiet=quiet, important=True)
    return True


def patch_browser_config(domains: list[str], *, dry: bool, quiet: bool) -> bool:
    if not domains:
        return False
    path = browser_toml()
    urls: list[str] = []
    for domain in domains:
        urls.append(f"https://{domain}")
        urls.append(f"https://*.{domain}")
    if not path.exists():
        body = (
            'approval_mode = "never_ask"\n'
            'history_approval_mode = "never_ask"\n'
            'download_approval_mode = "never_ask"\n'
            'upload_approval_mode = "never_ask"\n'
            "full_cdp_access_enabled = true\n\n"
        )
        for table in ("origins", "downloads", "uploads", "full_cdp"):
            inner = ",\n".join(f'  "{u}"' for u in urls)
            body += f"[{table}]\nallowed = [\n{inner},\n]\ndenied = []\n\n"
        if dry:
            log(f"would create: {path}", quiet=quiet)
            return True
        path.parent.mkdir(parents=True, exist_ok=True)
        write_text(path, body)
        log(f"created: {path}", quiet=quiet)
        return True
    text = read_text(path)
    original = text
    for table in ("origins", "downloads", "uploads", "full_cdp"):
        text = merge_allowed_array(text, table, urls)
    if text == original:
        log(f"unchanged: {path}", quiet=quiet)
        return False
    if dry:
        log(f"would patch: {path}", quiet=quiet)
        return True
    backup(path)
    write_text(path, text)
    log(f"patched: {path}", quiet=quiet, important=True)
    return True


def patch_cua_mcp(*, dry: bool, quiet: bool) -> int:
    root = plugin_cache() / "unified-computer-use"
    if not root.exists():
        log("no unified-computer-use plugin cache (skip)", quiet=quiet)
        return 0
    changed = 0
    wrap = str(wrapper_path())
    for mcp in sorted(root.glob("*/.mcp.json")):
        data = json.loads(read_text(mcp))
        env = data.get("mcpServers", {}).get("cua_repl", {}).get("env")
        if not isinstance(env, dict):
            continue
        before = dict(env)
        env["BROWSER_USE_SECURITY_MODE"] = MODE
        if not IS_WIN:
            # macOS routes the child through the exec wrapper. On Windows there
            # is nothing to wrap, so the official node_repl path stays as-is.
            env["CUA_REPL_NODE_REPL_PATH"] = wrap
        if env == before:
            continue
        if dry:
            log(f"would patch: {mcp}", quiet=quiet)
            changed += 1
            continue
        backup(mcp)
        write_text(mcp, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
        log(f"patched: {mcp}", quiet=quiet, important=True)
        changed += 1
    return changed


