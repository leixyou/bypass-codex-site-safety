#!/usr/bin/env python3
"""Enable Codex Browser Use local-testing mode (macOS + Windows).

Codex Browser Use calls https://chatgpt.com/backend-api/aura/site_status
before every navigation. That cloud check blocks legitimate sites
(Taobao, 1688, Pixiv, ...) even when the user allowlisted them.

The bundled plugin already understands:

    BROWSER_USE_SECURITY_MODE=disabled-for-local-testing

which adds `check-url-site-status` (and friends) to bypassedSecurityChecks,
so `check-url-site-status` is skipped entirely. This tool turns that flag on
locally and, optionally, expands origin allowlists. Codex/ChatGPT updates
rewrite ~/.codex/config.toml; `install --persist` installs a watcher that
re-applies the same patch (LaunchAgent on macOS, Scheduled Task on Windows).

Platform differences
--------------------
macOS: the flag is injected by pointing [mcp_servers.node_repl] `command` at a
       bash wrapper that exports the variable and `exec`s the signed node_repl
       (keeps the native-pipe code-signing identity intact).

Windows: no wrapper is needed or wanted. [mcp_servers.node_repl] already has an
       `env` table that Codex passes to node_repl.exe, so the variable is set
       there directly and `command` is left untouched.
"""
