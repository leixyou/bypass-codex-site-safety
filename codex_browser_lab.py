def save_state(domains: list[str], preset: str | None, interval: int | None = None) -> None:
    wrappers_dir().mkdir(parents=True, exist_ok=True)
    payload = {
        "preset": preset,
        "domains": domains,
        "python": sys.executable,
    }
    if interval is not None:
        payload["interval_min"] = interval
    write_text(state_path(), json.dumps(payload, indent=2) + "\n")


def load_state() -> dict:
    if not state_path().exists():
        return {"domains": [], "preset": None}
    try:
        return json.loads(read_text(state_path()))
    except (OSError, ValueError):
        return {"domains": [], "preset": None}


def install_self(*, quiet: bool) -> None:
    src = Path(__file__).resolve()
    dst = installed_script()
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src != dst:
        shutil.copy2(src, dst)
        if not IS_WIN:
            dst.chmod(dst.stat().st_mode | stat.S_IXUSR)
    log(f"installed tool: {dst}", quiet=quiet)


# --------------------------------------------------------------------------
# persistence: macOS LaunchAgent
# --------------------------------------------------------------------------
def persist_macos(*, quiet: bool) -> None:
    install_self(quiet=quiet)
    agent = launch_agent_path()
    agent.parent.mkdir(parents=True, exist_ok=True)
    plist = {
        "Label": LABEL,
        "ProgramArguments": [
            sys.executable,
            str(installed_script()),
            "repair",
        ],
        "WatchPaths": [
            str(config_toml()),
            str(plugin_cache()),
        ],
        "RunAtLoad": True,
        "StandardOutPath": str(log_path()),
        "StandardErrorPath": str(log_path()),
    }
    agent.write_bytes(plistlib.dumps(plist))
    uid = os.getuid()
    target = f"gui/{uid}"
    subprocess.run(["launchctl", "bootout", target, str(agent)], check=False, capture_output=True)
    subprocess.run(["launchctl", "unload", str(agent)], check=False, capture_output=True)
    loaded = subprocess.run(
        ["launchctl", "bootstrap", target, str(agent)], capture_output=True, text=True
    )
    if loaded.returncode != 0:
        loaded = subprocess.run(
            ["launchctl", "load", str(agent)], capture_output=True, text=True
        )
    if loaded.returncode != 0:
        raise SystemExit(loaded.stderr.strip() or "launchctl load failed")
    log(f"persist: {agent}", quiet=quiet)


def unpersist_macos(*, quiet: bool) -> None:
    agent = launch_agent_path()
    if agent.exists():
        uid = os.getuid()
        subprocess.run(
            ["launchctl", "bootout", f"gui/{uid}", str(agent)],
            check=False,
            capture_output=True,
        )
        subprocess.run(["launchctl", "unload", str(agent)], check=False, capture_output=True)
        agent.unlink()
        log(f"removed LaunchAgent: {agent}", quiet=quiet)
    else:
        log("no LaunchAgent installed", quiet=quiet)


# --------------------------------------------------------------------------
# persistence: Windows Scheduled Task
# --------------------------------------------------------------------------
def _python_for_task() -> str:
    exe = Path(sys.executable)
    if IS_WIN:
        pyw = exe.with_name("pythonw.exe")
        if pyw.exists():
            return str(pyw)
    return str(exe)


def write_repair_cmd(*, quiet: bool) -> Path:
    """Tiny .cmd shim so the scheduled task never needs nested quoting."""
    cmd = win_repair_cmd()
    cmd.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "@echo off\r\n"
        "rem Generated by codex-browser-lab; re-applies the security-mode patch.\r\n"
        f'"{_python_for_task()}" "{installed_script()}" repair >> "{log_path()}" 2>&1\r\n'
    )
    if not cmd.exists() or read_text(cmd) != body:
        write_text(cmd, body)
    log(f"repair shim: {cmd}", quiet=quiet)
    return cmd


def _schtasks(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["schtasks", *args], capture_output=True, text=True, errors="replace"
    )


def persist_windows(*, quiet: bool, interval: int = DEFAULT_WIN_INTERVAL_MIN) -> None:
    if interval < 1:
        interval = 1
    install_self(quiet=quiet)
    shim = write_repair_cmd(quiet=quiet)
    tr = f'"{shim}"'
    created: list[str] = []
    errors: list[str] = []

    r = _schtasks(
        "/Create", "/TN", WIN_TASK, "/TR", tr,
        "/SC", "MINUTE", "/MO", str(interval), "/F",
    )
    if r.returncode == 0:
        created.append(WIN_TASK)
    else:
        errors.append(f"{WIN_TASK}: {(r.stderr or r.stdout).strip()}")

    r = _schtasks("/Create", "/TN", WIN_TASK_LOGON, "/TR", tr, "/SC", "ONLOGON", "/F")
    if r.returncode == 0:
        created.append(WIN_TASK_LOGON)
    else:
        errors.append(f"{WIN_TASK_LOGON}: {(r.stderr or r.stdout).strip()}")

    if not created:
        raise SystemExit("could not register a scheduled task:\n  " + "\n  ".join(errors))
    for name in created:
        log(f"persist: scheduled task {name}", quiet=quiet)
    for err in errors:
        log(f"warn: task not registered - {err}", quiet=quiet, important=True)
    if WIN_TASK_LOGON not in created:
        log(
            "note: the logon task is optional. Registering an ONLOGON trigger needs an "
            "elevated shell; the periodic task already re-applies the patch shortly "
            "after a reboot.",
            quiet=quiet,
        )


def unpersist_windows(*, quiet: bool) -> None:
    removed = False
    for name in (WIN_TASK, WIN_TASK_LOGON):
        r = _schtasks("/Delete", "/TN", name, "/F")
        if r.returncode == 0:
            log(f"removed scheduled task: {name}", quiet=quiet)
            removed = True
    if not removed:
        log("no scheduled task installed", quiet=quiet)
    shim = win_repair_cmd()
    if shim.exists():
        shim.unlink()
        log(f"removed repair shim: {shim}", quiet=quiet)


def persist(*, quiet: bool, interval: int = DEFAULT_WIN_INTERVAL_MIN) -> None:
    if IS_MAC:
        persist_macos(quiet=quiet)
    elif IS_WIN:
        persist_windows(quiet=quiet, interval=interval)
    else:
        raise SystemExit("--persist is supported on macOS and Windows only")


def unpersist(*, quiet: bool) -> None:
    if IS_MAC:
        unpersist_macos(quiet=quiet)
    elif IS_WIN:
        unpersist_windows(quiet=quiet)


def _task_state(name: str) -> str:
    r = _schtasks("/Query", "/TN", name)
    if r.returncode == 0:
        return "installed"
    message = f"{r.stdout or ''} {r.stderr or ''}".lower()
    if "cannot find" in message or "找不到" in message:
        return "absent"
    # A denied/failed query must not be reported as "absent".
    return "unknown"


def persist_status() -> str:
    if IS_MAC:
        agent = launch_agent_path()
        return f"LaunchAgent {agent} exists={agent.exists()}"
    if IS_WIN:
        return " ".join(
            f"{name}={_task_state(name)}" for name in (WIN_TASK, WIN_TASK_LOGON)
        )
    return "n/a"


