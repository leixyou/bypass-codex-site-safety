def cmd_install(args: argparse.Namespace) -> int:
    domains = list(args.allow)
    if args.preset:
        domains.extend(PRESETS[args.preset])
    seen: set[str] = set()
    uniq: list[str] = []
    for d in domains:
        d = d.strip().lower().lstrip(".")
        if d and d not in seen:
            seen.add(d)
            uniq.append(d)

    node_repl = official_node_repl()
    if node_repl is None:
        target = "Codex/ChatGPT node_repl" if IS_WIN else "ChatGPT.app / Codex.app node_repl"
        raise SystemExit(f"{target} not found")
    if IS_WIN:
        log(f"node_repl: {node_repl}", quiet=args.quiet)
    else:
        ensure_wrapper(dry=args.dry_run, quiet=args.quiet)

    patch_config(uniq, dry=args.dry_run, quiet=args.quiet)
    patch_browser_config(uniq, dry=args.dry_run, quiet=args.quiet)
    patch_cua_mcp(dry=args.dry_run, quiet=args.quiet)
    if not args.dry_run:
        interval = getattr(args, "interval", None)
        save_state(uniq, args.preset, interval)
        if args.persist:
            persist(quiet=args.quiet, interval=interval or DEFAULT_WIN_INTERVAL_MIN)
        else:
            install_self(quiet=args.quiet)
    restart_hint = "restart Codex / ChatGPT Desktop" if IS_WIN else "restart ChatGPT.app"
    log(
        f"done. start a NEW Codex thread (or {restart_hint}) so node_repl picks up the env.",
        quiet=args.quiet,
    )
    return 0


def cmd_repair(args: argparse.Namespace) -> int:
    state = load_state()
    ns = argparse.Namespace(
        allow=state.get("domains") or [],
        preset=None,
        persist=False,
        dry_run=False,
        quiet=True,
        interval=state.get("interval_min"),
    )
    try:
        return cmd_install(ns)
    except SystemExit as exc:
        _append_log(f"repair failed: {exc}")
        raise
    except Exception as exc:  # noqa: BLE001 - a watcher must never die loudly
        _append_log(f"repair error: {exc!r}")
        return 1


def _append_log(line: str) -> None:
    try:
        wrappers_dir().mkdir(parents=True, exist_ok=True)
        stamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        with log_path().open("a", encoding="utf-8") as fh:
            fh.write(f"{stamp} {line}\n")
    except OSError:
        pass


def cmd_uninstall(args: argparse.Namespace) -> int:
    unpersist(quiet=args.quiet)
    path = config_toml()
    if path.exists():
        text = read_text(path)
        bin_path = official_node_repl()
        if not IS_WIN and bin_path is not None and table_span(text, "mcp_servers.node_repl"):
            text = set_key(text, "mcp_servers.node_repl", "command", str(bin_path))
        text = remove_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE")
        if not args.dry_run:
            write_text(path, text)
            log(f"restored node_repl in {path}", quiet=args.quiet)
    root = plugin_cache() / "unified-computer-use"
    wrap = str(wrapper_path())
    bin_path = official_node_repl()
    if root.exists():
        for mcp in root.glob("*/.mcp.json"):
            data = json.loads(read_text(mcp))
            env = data.get("mcpServers", {}).get("cua_repl", {}).get("env")
            if not isinstance(env, dict):
                continue
            env.pop("BROWSER_USE_SECURITY_MODE", None)
            if bin_path is not None and env.get("CUA_REPL_NODE_REPL_PATH") == wrap:
                env["CUA_REPL_NODE_REPL_PATH"] = str(bin_path)
            if not args.dry_run:
                write_text(mcp, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
                log(f"restored {mcp}", quiet=args.quiet)
    log("origin allowlists were left in place; delete them manually if you want.", quiet=args.quiet)
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    print(f"platform            {sys.platform}")
    print(f"CODEX_HOME          {codex_home()}")
    if IS_WIN:
        print(f"official node_repl  {official_node_repl()}")
        print(f"persist             {persist_status()}")
        print(f"repair shim         {win_repair_cmd()} exists={win_repair_cmd().exists()}")
    else:
        print(f"wrapper             {wrapper_path()} exists={wrapper_path().exists()}")
        print(f"official node_repl  {official_node_repl()}")
        print(f"LaunchAgent         {launch_agent_path()} exists={launch_agent_path().exists()}")

    cfg = config_toml()
    ok = False
    if cfg.exists():
        text = read_text(cfg)
        cmd = get_key(text, "mcp_servers.node_repl", "command")
        mode = get_key(text, "mcp_servers.node_repl.env", "BROWSER_USE_SECURITY_MODE")
        print(f"config command      {cmd}")
        print(f"config security     {mode}")
        if IS_WIN:
            official = official_node_repl()
            # On Windows `command` must remain the official binary.
            cmd_ok = official is not None and cmd is not None and Path(cmd) == official
        else:
            cmd_ok = cmd == str(wrapper_path())
        ok = cmd_ok and mode == MODE
        print(f"config ok           {ok}")
    else:
        print("config.toml         missing")

    rows = live_node_repl()
    if not rows:
        print("live node_repl      (none)")
    for pid, mode in rows:
        print(f"live pid={pid:<10} mode={mode}")
    if not ok:
        return 2
    if rows and all(m != MODE for _, m in rows):
        print("note: live processes still have the old env; start a new Codex thread.")
        return 3
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="codex-browser-lab",
        description="Turn on Codex Browser Use local-testing mode (skip aura/site_status).",
    )
    sub = p.add_subparsers(dest="cmd", required=True)

    def add_common(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--dry-run", action="store_true")
        sp.add_argument("--quiet", action="store_true")

    ins = sub.add_parser("install", help="patch local Codex/ChatGPT config")
    add_common(ins)
    ins.add_argument(
        "--persist",
        action="store_true",
        help="install a watcher that re-applies after updates "
        "(macOS LaunchAgent / Windows Scheduled Task)",
    )
    ins.add_argument(
        "--interval",
        type=int,
        metavar="MIN",
        help=f"Windows: re-check period in minutes (default {DEFAULT_WIN_INTERVAL_MIN})",
    )
    ins.add_argument("--preset", choices=sorted(PRESETS), help="origin allowlist preset")
    ins.add_argument(
        "--allow", action="append", default=[], metavar="DOMAIN",
        help="repeatable, e.g. --allow pixiv.net",
    )
    ins.set_defaults(func=cmd_install)

    st = sub.add_parser("status", help="show whether the patch is active")
    add_common(st)
    st.set_defaults(func=cmd_status)

    un = sub.add_parser("uninstall", help="restore official node_repl; keep origin allowlists")
    add_common(un)
    un.set_defaults(func=cmd_uninstall)

    rp = sub.add_parser("repair", help="re-apply last install (used by the watcher)")
    add_common(rp)
    rp.set_defaults(func=cmd_repair)

    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
