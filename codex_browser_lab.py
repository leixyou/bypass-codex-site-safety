def _windows_node_repl_pids() -> list[int]:
    """Enumerate node_repl.exe via toolhelp32 (no external tool, no shell)."""
    import ctypes
    from ctypes import wintypes

    TH32CS_SNAPPROCESS = 0x00000002
    INVALID_HANDLE_VALUE = ctypes.c_void_p(-1).value

    class PROCESSENTRY32W(ctypes.Structure):
        _fields_ = [
            ("dwSize", wintypes.DWORD),
            ("cntUsage", wintypes.DWORD),
            ("th32ProcessID", wintypes.DWORD),
            ("th32DefaultHeapID", ctypes.POINTER(ctypes.c_ulong)),
            ("th32ModuleID", wintypes.DWORD),
            ("cntThreads", wintypes.DWORD),
            ("th32ParentProcessID", wintypes.DWORD),
            ("pcPriClassBase", ctypes.c_long),
            ("dwFlags", wintypes.DWORD),
            ("szExeFile", wintypes.WCHAR * 260),
        ]

    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    k32.CreateToolhelp32Snapshot.restype = ctypes.c_void_p
    k32.CreateToolhelp32Snapshot.argtypes = [wintypes.DWORD, wintypes.DWORD]
    k32.Process32FirstW.argtypes = [ctypes.c_void_p, ctypes.POINTER(PROCESSENTRY32W)]
    k32.Process32NextW.argtypes = [ctypes.c_void_p, ctypes.POINTER(PROCESSENTRY32W)]
    k32.CloseHandle.argtypes = [ctypes.c_void_p]

    snapshot = k32.CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0)
    if not snapshot or snapshot == INVALID_HANDLE_VALUE:
        return []
    pids: list[int] = []
    try:
        entry = PROCESSENTRY32W()
        entry.dwSize = ctypes.sizeof(PROCESSENTRY32W)
        ok = k32.Process32FirstW(ctypes.c_void_p(snapshot), ctypes.byref(entry))
        while ok:
            if entry.szExeFile.lower() == "node_repl.exe":
                pids.append(int(entry.th32ProcessID))
            ok = k32.Process32NextW(ctypes.c_void_p(snapshot), ctypes.byref(entry))
    finally:
        k32.CloseHandle(ctypes.c_void_p(snapshot))
    return pids


def _read_windows_process_env(pid: int) -> dict[str, str] | None:
    """Read another same-user process's environment block via its PEB (read-only)."""
    import ctypes
    from ctypes import wintypes

    PROCESS_QUERY_INFORMATION = 0x0400
    PROCESS_VM_READ = 0x0010

    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    ntdll = ctypes.WinDLL("ntdll", use_last_error=True)

    k32.OpenProcess.restype = ctypes.c_void_p
    k32.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
    k32.ReadProcessMemory.restype = wintypes.BOOL
    k32.ReadProcessMemory.argtypes = [
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.c_void_p,
        ctypes.c_size_t,
        ctypes.POINTER(ctypes.c_size_t),
    ]
    k32.CloseHandle.argtypes = [ctypes.c_void_p]
    ntdll.NtQueryInformationProcess.restype = ctypes.c_long
    ntdll.NtQueryInformationProcess.argtypes = [
        ctypes.c_void_p,
        ctypes.c_ulong,
        ctypes.c_void_p,
        ctypes.c_ulong,
        ctypes.POINTER(ctypes.c_ulong),
    ]

    class PROCESS_BASIC_INFORMATION(ctypes.Structure):
        _fields_ = [
            ("Reserved1", ctypes.c_void_p),
            ("PebBaseAddress", ctypes.c_void_p),
            ("Reserved2", ctypes.c_void_p * 2),
            ("UniqueProcessId", ctypes.c_void_p),
            ("Reserved3", ctypes.c_void_p),
        ]

    handle = k32.OpenProcess(PROCESS_QUERY_INFORMATION | PROCESS_VM_READ, False, pid)
    if not handle:
        return None
    try:
        pbi = PROCESS_BASIC_INFORMATION()
        ret = ctypes.c_ulong(0)
        status = ntdll.NtQueryInformationProcess(
            ctypes.c_void_p(handle), 0, ctypes.byref(pbi),
            ctypes.sizeof(pbi), ctypes.byref(ret),
        )
        if status != 0 or not pbi.PebBaseAddress:
            return None

        def read_ptr(address: int) -> int | None:
            buf = ctypes.c_void_p()
            n = ctypes.c_size_t(0)
            ok = k32.ReadProcessMemory(
                ctypes.c_void_p(handle), ctypes.c_void_p(address),
                ctypes.byref(buf), ctypes.sizeof(buf), ctypes.byref(n),
            )
            return buf.value if ok else None

        # PEB->ProcessParameters (x64 +0x20), then
        # RTL_USER_PROCESS_PARAMETERS->Environment (x64 +0x80).
        params = read_ptr(pbi.PebBaseAddress + 0x20)
        if not params:
            return None
        env_ptr = read_ptr(params + 0x80)
        if not env_ptr:
            return None

        blob = bytearray()
        address = env_ptr
        chunk = 4096
        while len(blob) < 1024 * 1024:
            buf = ctypes.create_string_buffer(chunk)
            n = ctypes.c_size_t(0)
            ok = k32.ReadProcessMemory(
                ctypes.c_void_p(handle), ctypes.c_void_p(address),
                buf, chunk, ctypes.byref(n),
            )
            if not ok or n.value == 0:
                break
            blob += buf.raw[: n.value]
            if blob.endswith(b"\x00\x00"):
                break
            address += n.value

        text = bytes(blob).decode("utf-16-le", errors="replace")
        env: dict[str, str] = {}
        for item in text.split("\x00"):
            if not item or item.startswith("=") or "=" not in item:
                continue
            key, value = item.split("=", 1)
            env[key] = value
        return env
    except OSError:
        return None
    finally:
        k32.CloseHandle(ctypes.c_void_p(handle))


def live_node_repl() -> list[tuple[str, str]]:
    if IS_WIN:
        rows = []
        for pid in _windows_node_repl_pids():
            env = _read_windows_process_env(pid)
            if env is None:
                rows.append((str(pid), "<unreadable>"))
            else:
                rows.append((str(pid), env.get("BROWSER_USE_SECURITY_MODE", "<unset>")))
        return rows
    try:
        pids = subprocess.check_output(
            ["pgrep", "-f", "/cua_node/bin/node_repl"], text=True
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    rows = []
    for pid in pids.split():
        try:
            env = subprocess.check_output(
                ["ps", "eww", "-p", pid], text=True, errors="replace"
            )
        except subprocess.CalledProcessError:
            continue
        mode = "<unset>"
        for part in env.replace(" ", "\n").split("\n"):
            if part.startswith("BROWSER_USE_SECURITY_MODE="):
                mode = part.split("=", 1)[1]
                break
        rows.append((pid, mode))
    return rows


